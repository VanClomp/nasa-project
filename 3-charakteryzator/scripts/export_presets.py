"""Export the known Moon / Mars sites of Component 3 as the frontend's landing-site presets.

Writes 1-webpage/presets.php (a PHP file returning an array; the frontend Dockerfile copies *.php, so no build change).
Single source of truth: moon_sites.SITES / outputs/moon_sites.json and marslib.SITES / mars_model.STATION_FILES, so the
site picker, the characterizer's `extra.site` and the local/global model badge all use the same sites and coordinates.

Moon coordinates come from outputs/moon_sites.json: for Artemis regions given only approximately ('region, approx')
that file holds the refined best-lit flat point, which is the point the characterizer actually describes.
Mars `local` = the site has surface station records (the characterizer answers with model "local" there).

Usage:  python scripts/export_presets.py            (from 3-charakteryzator/)
Re-run after changing a site list or regenerating outputs/moon_sites.json.
"""
import json, os, sys
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(HERE, 'scripts'))
OUT = os.path.join(HERE, '..', '1-webpage', 'presets.php')

MOON_GROUPS = [   # (group label, predicate on moon_sites kind)
    ('Artemis III – regiony kandydackie NASA (2024)', lambda k: k == 'Artemis region'),
    ('Biegun południowy – najlepsze oświetlenie', lambda k: k == 'Polar illumination peak'),
    ('Tunele lawowe (świetliki)', lambda k: k == 'Lava-tube skylight'),
    ('Dotychczasowe lądowania', lambda k: k.startswith('Landed')),
]


def moon():
    import moon_sites
    refined = {r['site']['id']: r['coordinates'] for r in
               json.load(open(os.path.join(HERE, 'outputs', 'moon_sites.json')))['results'] if r.get('site')}
    out = []
    for label, pred in MOON_GROUPS:
        for s in moon_sites.SITES:
            k = s['kind']
            if not pred(k): continue
            c = refined.get(s['id'], dict(lat=s['lat'], lon=s['lon']))
            if k == 'Artemis region':
                desc = 'Region kandydacki Artemis III (NASA)'
            elif k == 'Polar illumination peak':
                desc = 'Grzbiet Shackleton–de Gerlache, najdłuższe oświetlenie'
            elif k == 'Lava-tube skylight':
                desc = 'Świetlik tunelu lawowego (LROC)'
            else:
                desc = 'Lądowanie: ' + k[k.find('(') + 1:k.rfind(')')] if '(' in k else k
            name = s['name'] + (f" ({k[k.find('(') + 1:k.rfind(')')]})" if k.startswith('Landed') and '(' in k else '')
            out.append(dict(id=s['id'], name=name, lat=round(float(c['lat']), 3),
                            lon=round(((float(c['lon']) + 180) % 360) - 180, 3), group=label, desc=desc, local=False,
                            station_months=[]))
    return out


def mars():
    import marslib, mars_model
    stations = set(mars_model.STATION_FILES)
    station_keys = ('air_temp_min', 'air_temp_max', 'air_temp_mean', 'ground_temp_min', 'ground_temp_max',
                    'ground_temp_mean', 'pressure', 'wind_mean')      # = service/contract.py STATION_PARAMS
    months_with_data = {sid: [k for k in range(1, 13)
                              if any(x in mars_model.station_month(sid, k) for x in station_keys)] for sid in stations}
    groups = [('Przyszłe misje – kandydaci', lambda s: s['kind'] == 'Candidate'),
              ('Lądowiska z danymi stacji (model lokalny)', lambda s: s['kind'] != 'Candidate' and s['id'] in stations),
              ('Pozostałe lądowiska', lambda s: s['kind'] != 'Candidate' and s['id'] not in stations)]
    out = []
    for label, pred in groups:
        for s in marslib.SITES:
            if not pred(s): continue
            desc = ('Kandydat: ' if s['kind'] == 'Candidate' else 'Lądowanie: ') + s['mission']
            name = s['name'] + (f" ({s['mission']})" if s['kind'] != 'Candidate' else '')
            out.append(dict(id=s['id'], name=name, lat=round(float(s['lat']), 3),
                            lon=round(((float(s['lon']) + 180) % 360) - 180, 3), group=label, desc=desc,
                            local=s['id'] in stations, station_months=months_with_data.get(s['id'], [])))
    return out


def php(v, ind=0):
    p = '    ' * ind
    if isinstance(v, dict):
        return '[' + ', '.join(f"'{k}' => {php(x)}" for k, x in v.items()) + ']'
    if isinstance(v, list):
        return '[\n' + ''.join(f"{p}    {php(x, ind + 1)},\n" for x in v) + p + ']'
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, (int, float)): return repr(v)
    return "'" + str(v).replace('\\', '\\\\').replace("'", "\\'") + "'"


if __name__ == '__main__':
    data = dict(moon=moon(), mars=mars())
    body = ('<?php\n// GENERATED by 3-charakteryzator/scripts/export_presets.py - do not edit by hand; re-run the script.\n'
            '// Landing-site presets: NASA Artemis III candidate regions and other known Moon sites; Mars landing sites\n'
            '// and future-mission candidates. Coordinates match the characterizer (refined points for approximate regions).\n'
            'return [\n' + ''.join(f"    '{b}' => {php(v, 1)},\n" for b, v in data.items()) + '];\n')
    open(OUT, 'w', encoding='utf-8').write(body)
    print(f'wrote {os.path.normpath(OUT)}: moon {len(data["moon"])}, mars {len(data["mars"])} sites')
